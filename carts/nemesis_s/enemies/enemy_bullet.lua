local minimum_aim_distance<const> = 0x30
local angle_by_delta<const>: *u8 = enemy_bullet_angle_by_delta
local velocity_by_angle<const>: *word = enemy_bullet_velocity_by_angle

local new_enemy_bullet_collider<const> = collider_2d_component.factory_for_sprite({
	id_local = 0,
	layer = collision_enemy_projectile_layer,
	mask = collision_enemy_projectile_mask,
})

-- Returns no velocity inside the source game's close-range admission boundary.
-- Otherwise the returned words can be written directly to the fixed-point
-- movement component used by every enemy bullet.
function enemy_bullet.aim_velocity(delta_x, delta_y)
	local abs_x<const> = math.abs(delta_x)
	local abs_y<const> = math.abs(delta_y)
	local coarse_x<const> = abs_x & 0xf0
	if coarse_x + abs_y < minimum_aim_distance then
		return nil
	end

	local angle<const> = angle_by_delta[coarse_x + (abs_y >> 4)]
	local velocity_x<const> = velocity_by_angle[angle]
	local velocity_y<const> = velocity_by_angle[0x3f - angle]
	return delta_x < 0 and -velocity_x or velocity_x,
		delta_y < 0 and -velocity_y or velocity_y
end

function enemy_bullet:update_flying()
	if self.x < enemy_bullet_size
	or self.x > playfield_width
	or self.y < enemy_bullet_size
	or self.y > playfield_height
	or self.stage:is_solid_pixel(self.x + 2, self.y + 2) then
		self:mark_for_disposal()
	end
end

function enemy_bullet:ctor()
	self.motion = self:get_component(fixed_point_velocity_component)
end

local define_fsm<const> = function()
	fsm_library.register(ids_enemy_bullet_fsm, {
		initial = 'flying',
		states = {
			flying = {
				update = enemy_bullet.update_flying,
				on = {
					['overlap.begin'] = sprite_object.mark_for_disposal,
				},
			},
		},
	})
end

local register_definition<const> = function()
	prefab.define({
		def_id = ids_enemy_bullet_def,
		class = enemy_bullet,
		base = sprite_object,
		components = {
			new_enemy_bullet_collider,
			fixed_point_velocity_component.new,
			fsm_component.factory({ ids_enemy_bullet_fsm }),
		},
		defaults = {
			imgid = assets_enemy_bullet,
			force_field_hit = player_force_field_hit_standard,
			z = enemy_bullet_draw_z,
		},
	})
end

function enemy_bullet.register()
	define_fsm()
	register_definition()
end

return enemy_bullet
