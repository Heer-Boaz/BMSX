test('moving an authored input onto a different running LuaProgram deactivates only the displaced destination view', t => {
	const program = "local p=require('cartlib/progression'); p.compile_program({rules={},filters={},handlers={}})";
	const f = createActualSourcePanes(t, false, [['program.lua', program], ['cartlib/progression.lua', '']]);
	const resource = f.sources.catalog.resolveResource({ contextId: f.sources.systemContextId, path: 'program.lua' })!;
	f.editor.luaPrograms.openResource(f.secondGroup, resource, 'progression');
	const displaced = f.secondGroup.model.activeTab;
	assert.ok(displaced instanceof LuaProgramInput);
	displaced.inspectRuntime(f.editor.commands.transport); displaced.interaction.running = true;
	const transport = displaced.interaction.transport, cycles = f.host.runtime.machine.scheduler.nowCycles;
	f.firstGroup.activate(f.firstInput.id);
	assert.equal(f.editor.editorParts.moveEditor(f.firstPart.activeGroup, f.firstInput, f.secondPart.activeGroup, f.editor.editorClose), true); f.update();
	assert.ok(f.secondGroup.model.activeTab === f.firstInput);
	assert.ok(f.secondGroup.model.findById(displaced.id) === displaced);
	assert.equal(displaced.interaction.running, false, 'only source detachment is a move; replacing the destination is normal deactivation');
	assert.ok(displaced.interaction.transport === transport);
	assert.equal(displaced.workingCopy.buffer.getText(), program);
	assert.equal(f.host.runtime.machine.scheduler.nowCycles, cycles);
});

