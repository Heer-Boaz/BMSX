test('Behavior live inspection vetoes transfer, then its same authored graph and source lease move intact', async t => {
	const source = "local t=require('cartlib/behaviour_tree/library'); t.register('kept',{root={type='sequence',children={{type='wait',duration_ticks=1}}}})";
	const f = createActualSourcePanes(t, false, [['tree.lua', source], ['cartlib/behaviour_tree/library.lua', '']]);
	const resource = f.sources.catalog.resolveResource({ contextId: f.sources.systemContextId, path: 'tree.lua' })!;
	const model = resolveLuaTextFileModel(editorTextModelService, f.sources.catalog, resource), input = f.editor.behaviorLens.createInput(model, 'graph');
	f.firstGroup.openEditor(input); selectBehaviorLensDefinition(input.view, input.view.document.definitions[0].rowKey); input.updateDefinition();
	input.view.selection = { kind: 'node', rowKey: input.view.source.nodes.at(-1)!.rowKey }; f.update();
	const view = captureBehaviorLensView(input), cycles = f.host.runtime.machine.scheduler.nowCycles;
	const inspection = new BehaviorRuntimeInspection(f.sources, f.editor.luaPrograms.guest, f.host.rewind, -1,
		f.sources.currentBlua32Media.system!, undefined, f.editor.commands.transport);
	input.runtimeInspection = inspection;
	assert.equal(f.editor.editorParts.moveEditor(f.firstPart.activeGroup, input, f.secondPart.activeGroup, f.editor.editorClose), false);
	assert.ok(f.firstGroup.model.activeTab === input); assert.ok(input.runtimeInspection === inspection);
	input.runtimeInspection = undefined; inspection.dispose();
	assert.equal(f.editor.editorParts.moveEditor(f.firstPart.activeGroup, input, f.secondPart.activeGroup, f.editor.editorClose), true); f.update();
	assert.ok(f.secondGroup.model.activeTab === input); assert.ok(input.getWorkingCopies().includes(model));
	assert.deepEqual(captureBehaviorLensView(input), view);
	f.editor.commands.execute('behaviorLens.source', f.secondGroup.panes.activePane!.commandTarget.commandContext); await setImmediate(); f.update();
	const code = f.secondGroup.panes.activePane!.input;
	assert.ok(code?.kind === 'code_editor' && code.workingCopy === model);
	model.pushEditOperations([{ offset: 0, deleteLength: 0, text: '-- retained lease\n' }]);
	f.editor.behaviorLens.updateView(input);
	assert.ok(input.isDirty() && model.canUndo); assert.ok(input.getWorkingCopies().includes(model));
	assert.equal(f.host.runtime.machine.scheduler.nowCycles, cycles);
});

