test('busy AEM refuses collision disposal but moves its same operation to a new window with destination-local Add', async t => {
	const f = createActualSourcePanes(t), path = 'events.aem.yaml';
	const source = `events:\n${Array.from({ length: 24 }, (_, index) => `  event_${index}: { channel: sfx, rules: [] }\n`).join('')}`;
	f.sources.catalog.registerTextSources(f.sources.systemContextId, [{ type: 'aem', resid: 'events', source_path: path }]);
	const resource = f.sources.catalog.resolveResource({ contextId: f.sources.systemContextId, path })!;
	const model = editorTextModelService.retain(resource, 'aem', source), input = new AemEditorInput(model), receiver = new AemEditorInput(model);
	model.pushEditOperations([{ offset: 0, deleteLength: 0, text: '# retained\n' }]);
	f.firstGroup.openEditor(input); f.secondGroup.openEditor(receiver); f.firstGroup.activate(input.id); f.update();
	input.tree.selectionIndex = input.tree.rows.findIndex(row => row.element.key === '["events"]');
	input.applying = true;
	const view = captureWorkbenchTreeView(input.tree, element => element.key), version = model.version;
	const originPane = f.firstGroup.panes.activePane!, count = f.editor.editorParts.documents.length;
	assert.equal(f.editor.editorParts.moveEditor(f.firstPart.activeGroup, input, f.secondPart.activeGroup, f.editor.editorClose), false);
	assert.ok(f.firstGroup.model.activeTab === input && f.firstGroup.panes.activePane === originPane);
	assert.ok(f.secondGroup.model.activeTab === receiver); assert.equal(f.editor.editorParts.documents.length, count);
	assert.equal(f.editor.editorParts.moveEditor(f.firstPart.activeGroup, input, 'new', f.editor.editorClose), true); f.update();
	const destination = f.editor.editorParts.activePart;
	assert.ok(destination !== f.firstPart && destination !== f.secondPart && destination.activeGroup.model.activeTab === input);
	assert.equal(input.applying, true); assert.deepEqual(captureWorkbenchTreeView(input.tree, element => element.key), view);
	assert.ok(input.workingCopy === model && model.canUndo); assert.equal(model.version, version);
	f.editor.commands.execute('aem.add', destination.activeGroup.panes.activePane!.commandTarget.commandContext);
	assert.equal(destination.quickInput.visible, true); assert.equal(f.firstPart.quickInput.visible, false);
	assert.ok(inputFocus.target === destination.quickInput.field.focusTarget);
	f.key('Escape'); assert.equal(destination.quickInput.visible, false);
	f.editor.commands.execute('aem.source', destination.activeGroup.panes.activePane!.commandTarget.commandContext); await setImmediate(); f.update();
	const code = destination.activeGroup.panes.activePane!.input;
	assert.ok(code?.kind === 'code_editor' && code.workingCopy === model);
	assert.equal(model.buffer.getText(), '# retained\n' + source); assert.equal(model.version, version);
});

