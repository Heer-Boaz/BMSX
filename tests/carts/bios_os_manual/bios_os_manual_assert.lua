local storage<const> = require('results')
local result<const>: *bios_os_manual_result = storage.result
local observations<const> = storage.observations

return {
	kind = 'integration',
	tests = {
		time_and_calendar_observations = function(t)
			t:wait_until('time and calendar observations complete', function()
				return result.completed == 1
			end, 8)
			-- The three live readings are deliberately not pinned to constants.
			assert(result.time_sample == result.time_sample // 1)
			assert(result.nil_time_sample == result.nil_time_sample // 1)
			assert(result.clock_sample >= 0 and result.clock_sample < 4294967.296)
			assert(result.noon_timestamp == 43200)
			assert(observations.noon.year == 1970)
			assert(observations.noon.month == 1)
			assert(observations.noon.day == 1)
			assert(observations.noon.hour == 12)
			assert(observations.noon.min == 0)
			assert(observations.noon.sec == 0)
			assert(observations.noon.wday == 5)
			assert(observations.noon.yday == 1)
			assert(observations.noon.isdst == false)
			assert(observations.noon.note == 'kept')
			assert(result.carried_timestamp == 1709168523)
			assert(observations.carried.year == 2024)
			assert(observations.carried.month == 2)
			assert(observations.carried.day == 29)
			assert(observations.carried.hour == 1)
			assert(observations.carried.min == 2)
			assert(observations.carried.sec == 3)
			assert(observations.carried.wday == 5)
			assert(observations.carried.yday == 60)
			assert(observations.carried.isdst == false)
			assert(observations.epoch.year == 1970)
			assert(observations.epoch.month == 1)
			assert(observations.epoch.day == 1)
			assert(observations.epoch.hour == 0)
			assert(observations.epoch.min == 0)
			assert(observations.epoch.sec == 0)
			assert(observations.epoch.wday == 5)
			assert(observations.epoch.yday == 1)
			assert(observations.epoch.isdst == false)
			assert(observations.before_epoch.year == 1969)
			assert(observations.before_epoch.month == 12)
			assert(observations.before_epoch.day == 31)
			assert(observations.before_epoch.hour == 23)
			assert(observations.before_epoch.min == 59)
			assert(observations.before_epoch.sec == 59)
			assert(observations.before_epoch.wday == 4)
			assert(observations.before_epoch.yday == 365)
			assert(observations.before_epoch.isdst == false)
			assert(observations.calendar == '2021 21 20 | 01 01  1 001')
			assert(observations.names == 'Fri Friday | Jan January Jan')
			assert(observations.clock ==
				'13:02:03 | 01 PM | 13:02 | 01:02:03 PM | 13:02:03 | 13:02:03')
			assert(observations.composites ==
				'2021-01-01 | 01/01/21 | 01/01/21 | Fri Jan 01 13:02:03 2021')
			assert(observations.weeks == '2021 | 2020 20-W53 | 00 00 | 5 5')
			assert(observations.next_iso_year == '2018-12-31 2019-W01-1')
			assert(observations.zone == 'offset +0000 zone BMSX %')
			assert(observations.separators == 'A\tB\nC')
			assert(observations.default_format == 'Thu Jan 01 00:00:00 1970')
			assert(observations.era_modifiers ==
				'Fri Jan 01 13:02:03 2021 | 20 01/01/21 13:02:03 21 2021')
			assert(observations.alternate_modifiers ==
				'01  1 13 01 01 02 03 | 5 00 53 5 00 21')
			assert(observations.missing_ok == false)
			assert(observations.missing_error == "field 'year' missing in date table")
			assert(observations.fraction_ok == false)
			assert(observations.fraction_error == "field 'hour' is not an integer")
			assert(observations.civil_range_ok == false)
			assert(observations.civil_range_error == "field 'year' is out-of-bound")
			assert(observations.time_range_ok == false)
			assert(observations.time_range_error == 'time is out-of-bound')
			assert(observations.conversion_ok == false)
			assert(observations.conversion_error == "invalid conversion specifier '%Q'")
			assert(observations.modifier_ok == false)
			assert(observations.modifier_error == "invalid conversion specifier '%Ea'")
			assert(result.elapsed == 90)
			assert(result.negative_difference == -1)
			assert(result.large_difference == 9007199254740992)
			assert(result.infinite_difference == math.huge)
			assert(result.indeterminate_difference ~= result.indeterminate_difference)
			assert(observations.t2_ok == false)
			assert(observations.t2_error == 'os.difftime t2 must be an integer.')
			assert(observations.t1_ok == false)
			assert(observations.t1_error == 'os.difftime t1 must be an integer.')
		end,
	},
}
