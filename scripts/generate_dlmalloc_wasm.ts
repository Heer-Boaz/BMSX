import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

import { MAPPED_PAGE_BYTE_SHIFT } from '../machine/ts/machine/memory/mapped_page';
import { MAIN_RAM_SIZE } from '../machine/ts/spec/bmsx/memory_map';

// The fixed Wasm backing has one host page after guest RAM. Reserve the
// beginning of that page for Memory's existing rewind-watch group plane.
const pageCount = (MAIN_RAM_SIZE >>> 16) + 1;
const memoryBytes = pageCount << 16;
const globalBase = MAIN_RAM_SIZE + (MAIN_RAM_SIZE >>> MAPPED_PAGE_BYTE_SHIFT) * Uint32Array.BYTES_PER_ELEMENT;
const stackBytes = 16 * 1024;

const root = resolve(import.meta.dirname, '..');
const source = join(root, 'machine/common/dlmalloc');
const destination = join(root, 'tests/helpers/native_heap/dlmalloc_wasm.generated.ts');
const clang = process.env.CLANG || 'clang-21';
const output = mkdtempSync(join(tmpdir(), 'bmsx-dlmalloc-wasm-'));
try {
	const wasm = join(output, 'dlmalloc.wasm');
	execFileSync(clang, [
		'--target=wasm32', '-std=c11', '-nostdlib', '-ffreestanding', '-mbulk-memory', '-O3', '-flto',
		'-fno-delete-null-pointer-checks',
		`-Wl,--no-entry,--import-memory,--global-base=${globalBase},--initial-memory=${memoryBytes},--max-memory=${memoryBytes}`,
		`-Wl,-z,stack-size=${stackBytes},--strip-all`,
		join(source, 'dlmalloc.c'), join(source, 'wasm_exports.c'), '-o', wasm,
	], { stdio: 'inherit' });
	const payload = readFileSync(wasm).toString('base64').match(/.{1,112}/g);
	const generated = `// Generated by scripts/generate_dlmalloc_wasm.ts with Clang/LLD 21. Do not edit.

export const DLMALLOC_WASM_PAGE_COUNT = ${pageCount};
export const DLMALLOC_WASM_BASE64 =
${payload.map(line => `\t'${line}'`).join(' +\n')};
`;
	if (process.argv.includes('--check')) {
		if (readFileSync(destination, 'utf8') !== generated) {
			throw new Error('The embedded dlmalloc Wasm module is not current. Run npx tsx scripts/generate_dlmalloc_wasm.ts.');
		}
	} else {
		writeFileSync(destination, generated);
	}
} finally {
	rmSync(output, { force: true, recursive: true });
}
