import { readFile } from 'node:fs/promises';
import { Msdfgen } from 'msdfgen-wasm';
import potpack from 'potpack';
import type { ScalableFontGlyph } from '../../machine/ts/render/host_overlay/scalable_font';
import { writeIfChanged } from './atlas_artifact';

const EM_SIZE = 8;
const RASTER_SIZE = 32;
const PIXEL_RANGE = 8;
const HEADER = '// Generated by scripts/render/scalable_font.ts. Do not edit by hand.\n';

/** A build-time font bake. Runtime renderers consume only metrics and linear distance texels. */
export async function generateScalableFontAtlas(): Promise<boolean> {
	const wasm = await readFile(require.resolve('msdfgen-wasm/wasm'));
	const generator = await Msdfgen.create(wasm.buffer.slice(wasm.byteOffset, wasm.byteOffset + wasm.byteLength));
	const characters = [...Array.from({ length: 95 }, (_, i) => i + 32),
		...Array.from({ length: 96 }, (_, i) => i + 160),
		...Array.from('Ĳĳ–—‘’“”•…€←↑→↓↔↕✓█', char => char.codePointAt(0)!)];
	const boxes: { glyph: ScalableFontGlyph; pixels: Uint8Array; w: number; h: number; x: number; y: number }[] = [];
	let lineHeight = 0;
	for (const style of ['Regular', 'Italic']) {
		generator.loadFont(await readFile(`hosts/fonts/jetbrains_mono/JetBrainsMono-${style}.ttf`));
		generator.loadGlyphs(characters);
		lineHeight = generator.metrics.lineHeight * EM_SIZE;
		for (const glyph of generator.glyphs) {
			const data = generator.computeGlpyhMsdfData(glyph, { size: RASTER_SIZE, range: PIXEL_RANGE });
			const pixels = data.width === 0 ? new Uint8Array(0) : new Uint8Array(generator.generateBitmap(glyph, data).buffer);
			boxes.push({ w: data.width + 2, h: data.height + 2, x: 0, y: 0, pixels, glyph: {
				id: `mono_${style}_${glyph.unicode}`, codepoint: glyph.unicode, italic: style === 'Italic',
				width: data.width / RASTER_SIZE * EM_SIZE, height: data.height / RASTER_SIZE * EM_SIZE,
				advance: glyph.advance * EM_SIZE,
				offsetX: -data.xTranslate * EM_SIZE,
				offsetY: (generator.metrics.ascenderY + data.yTranslate - data.height / RASTER_SIZE) * EM_SIZE,
				u: 0, v: 0, w: data.width, h: data.height,
			} });
		}
	}
	const { w: width, h: height } = potpack(boxes);
	const pixels = new Uint8Array(width * height * 4);
	for (const box of boxes) {
		const glyph = box.glyph;
		glyph.u = box.x + 1; glyph.v = box.y + 1;
		for (let row = 0; row < glyph.h; row++) {
			pixels.set(box.pixels.subarray(row * glyph.w * 4, (row + 1) * glyph.w * 4), ((glyph.v + row) * width + glyph.u) * 4);
		}
	}
	const glyphs = boxes.map(box => box.glyph).sort((a, b) => a.id < b.id ? -1 : 1);
	const distanceRange = PIXEL_RANGE / RASTER_SIZE * EM_SIZE;
	const ts = HEADER + [
		"import type { ScalableFontAtlas } from '../../../machine/ts/render/host_overlay/scalable_font';",
		"import pixels from '#bmsx/scalable-font-pixels';",
		'export const SCALABLE_FONT_ATLAS: ScalableFontAtlas = {',
		`\twidth: ${width}, height: ${height}, emSize: ${EM_SIZE}, lineHeight: ${lineHeight}, distanceRange: ${distanceRange},`,
		'\tpixels, srgb: false,',
		'\tglyphs: [', ...glyphs.map(glyph => `\t\t${JSON.stringify(glyph)},`), '\t],', '};', '',
	].join('\n');
	const cpp = HEADER + [
		'#include "render/host_overlay/scalable_font.h"',
		'#include "render/host_overlay/scalable_font_pixels.h"', 'namespace bmsx {', 'namespace {',
		'constexpr ScalableFontGlyph GLYPHS[] = {',
		...glyphs.map(glyph => `\t{${JSON.stringify(glyph.id)}, ${glyph.codepoint}u, ${glyph.italic}, {`
			+ [glyph.width, glyph.height, glyph.advance, glyph.offsetX, glyph.offsetY].map(value => `${value.toFixed(8)}F`).join(', ')
			+ `, ${glyph.u}u, ${glyph.v}u, ${glyph.w}u, ${glyph.h}u}},`),
		'};', '}', `const ScalableFontAtlas SCALABLE_FONT_ATLAS{{${width}u, ${height}u, SCALABLE_FONT_PIXELS, false}, ${EM_SIZE.toFixed(8)}F, ${lineHeight.toFixed(8)}F, ${distanceRange.toFixed(8)}F, GLYPHS};`, '}', '',
	].join('\n');
	const changed = await Promise.all([
		writeIfChanged('hosts/fonts/jetbrains_mono/scalable_font.generated.ts', ts),
		writeIfChanged('machine/cpp/render/host_overlay/scalable_font.generated.cpp', cpp),
		writeIfChanged('hosts/fonts/jetbrains_mono/scalable_font.rgba', pixels),
	]);
	return changed.some(Boolean);
}
